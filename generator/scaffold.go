// staticGoScaffold returns files shared by every generated SDK. The
// generated module is fully self-contained and compiles offline with the
// standard library alone. The taxonomy/runtime behavior intentionally
// mirrors the toolchain's own packages so error kinds and semantics stay
// identical between generation time and generated-client runtime.
func staticGoScaffold(module string) map[string]string {
	files := map[string]string{
		"go.mod":                     scaffoldGoMod(module),
		"sdkerrors/sdkerrors.go":     scaffoldSDKErrors(),
		"runtime/doc.go":             scaffoldRuntimeDoc(),
		"runtime/errors.go":          scaffoldRuntimeErrors(),
		"runtime/runtime.go":         scaffoldRuntimeClient(),
		"runtime/transport_local.go": scaffoldLocalTransport(),
	}
	for rel, content := range files {
		if rel == "go.mod" {
			continue
		}
		files[rel] = strings.ReplaceAll(content, "__MODULE__", module)
	}
	return files
}

func scaffoldGoMod(module string) string {
	return fmt.Sprintf("module %s\n\ngo 1.25.0\n", module)
}

func scaffoldSDKErrors() string {
	return `// Code generated by sdkgen; DO NOT EDIT BY HAND.
package sdkerrors

import (
	"errors"
	"fmt"
	"strings"
)

type Kind string

const (
	KindInput      Kind = "input_error"
	KindVersion    Kind = "version_incompatible"
	KindGeneration Kind = "generation_failed"
	KindRuntime    Kind = "runtime_call_failed"
)

type Error struct {
	Kind    Kind
	Reason  string
	Service string
	Version string
	Field   string
	Op      string
	Cause   error
}

func (e *Error) Error() string {
	var b strings.Builder
	b.WriteString(string(e.Kind))
	b.WriteString(": ")
	b.WriteString(e.Reason)
	var loc []string
	if e.Service != "" { loc = append(loc, "service="+e.Service) }
	if e.Version != "" { loc = append(loc, "version="+e.Version) }
	if e.Op != "" { loc = append(loc, "op="+e.Op) }
	if e.Field != "" { loc = append(loc, "field="+e.Field) }
	if len(loc) > 0 { b.WriteString(" [" + strings.Join(loc, ", ") + "]") }
	if e.Cause != nil { b.WriteString(": " + e.Cause.Error()) }
	return b.String()
}

func (e *Error) Unwrap() error { return e.Cause }

func New(kind Kind, reason string) *Error { return &Error{Kind: kind, Reason: reason} }
func Newf(kind Kind, format string, args ...any) *Error {
	return &Error{Kind: kind, Reason: fmt.Sprintf(format, args...)}
}
func (e *Error) WithService(s string) *Error { e.Service = s; return e }
func (e *Error) WithVersion(v string) *Error { e.Version = v; return e }
func (e *Error) WithField(f string) *Error { e.Field = f; return e }
func (e *Error) WithOp(o string) *Error { e.Op = o; return e }
func (e *Error) Wrap(c error) *Error { e.Cause = c; return e }

func IsKind(err error, kind Kind) bool {
	var se *Error
	if errors.As(err, &se) { return se.Kind == kind }
	return false
}
func AsError(err error) *Error {
	var se *Error
	if errors.As(err, &se) { return se }
	return nil
}
`
}

