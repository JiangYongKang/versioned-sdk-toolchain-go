func scaffoldRuntimeErrors() string {
	return `// Code generated by sdkgen; DO NOT EDIT BY HAND.
package runtime

import (
	"fmt"

	"` + importPlaceholder() + `/sdkerrors"
)

// StatusCode is the coarse backend status class used for error mapping.
type StatusCode int

const (
	StatusOK          StatusCode = 200
	StatusBadRequest  StatusCode = 400
	StatusConflict    StatusCode = 409
	StatusUnavailable StatusCode = 503
)

// Normalize maps a backend status plus transport error onto the stable
// taxonomy. Foreign error text is preserved only as a wrapped cause.
func Normalize(op string, status StatusCode, cause error) error {
	switch {
	case status == StatusBadRequest:
		return sdkerrors.New(sdkerrors.KindInput,
			"backend rejected the request as invalid").WithOp(op).Wrap(cause)
	case status == StatusConflict:
		return sdkerrors.New(sdkerrors.KindVersion,
			"backend reported a version conflict").WithOp(op).Wrap(cause)
	case status >= 500 || cause != nil:
		reason := "runtime call failed"
		if cause != nil {
			reason = fmt.Sprintf("runtime call failed: %v", cause)
		}
		return sdkerrors.New(sdkerrors.KindRuntime, reason).WithOp(op).Wrap(cause)
	default:
		return nil
	}
}
`
}

func scaffoldRuntimeClient() string {
	return `// Code generated by sdkgen; DO NOT EDIT BY HAND.
package runtime

import (
	"context"
	"encoding/json"

	"` + importPlaceholder() + `/sdkerrors"
)

// PreparedRequest is the serialized request handed to a transport.
type PreparedRequest struct {
	Service   string
	Version   string
	Operation string
	Body      []byte
}

// RawResponse is a transport response before decoding.
type RawResponse struct {
	Status StatusCode
	Body   []byte
}

// Transport executes a prepared request. Implementations must not leak
// foreign errors past the runtime client: they are normalized via
// Normalize.
type Transport interface {
	Call(ctx context.Context, req *PreparedRequest) (*RawResponse, error)
}

// Codec is the minimal serializer interface used by the runtime.
type Codec interface {
	Name() string
	Marshal(v any) ([]byte, error)
	Unmarshal(data []byte, v any) error
}

type jsonCodec struct{}

func (jsonCodec) Name() string { return "json" }
func (jsonCodec) Marshal(v any) ([]byte, error) {
	b, err := json.Marshal(v)
	if err != nil {
		return nil, sdkerrors.New(sdkerrors.KindRuntime, "failed to encode request").Wrap(err)
	}
	return b, nil
}
func (jsonCodec) Unmarshal(data []byte, v any) error {
	if err := json.Unmarshal(data, v); err != nil {
		return sdkerrors.New(sdkerrors.KindRuntime, "failed to decode response").Wrap(err)
	}
	return nil
}

// Request is one runtime invocation.
type Request struct {
	Service   string
	Version   string
	Operation string
	Codec     string
	Input     any
}

// Response is one runtime result.
type Response struct{ Raw []byte }

// Client executes operations against a Transport.
type Client struct {
	transport Transport
	codecs    map[string]Codec
}

// NewClient creates a runtime client with the JSON codec registered.
func NewClient(t Transport, extra ...Codec) *Client {
	c := &Client{transport: t, codecs: map[string]Codec{}}
	Register(c, jsonCodec{})
	for _, cd := range extra {
		Register(c, cd)
	}
	return c
}

// Register adds a codec to the client (duplicates rejected).
func Register(c *Client, cd Codec) {
	if cd == nil || cd.Name() == "" {
		return
	}
	c.codecs[cd.Name()] = cd
}

// Invoke serializes req, calls the transport and decodes the response.
// On success semantics are unchanged: out receives exactly the decoded
// payload. Every failure is a classified *sdkerrors.Error.
func (c *Client) Invoke(ctx context.Context, req *Request, out any) (*Response, error) {
	if req == nil {
		return nil, sdkerrors.New(sdkerrors.KindInput, "nil invoke request")
	}
	op := req.Service + "." + req.Operation
	name := req.Codec
	if name == "" {
		name = "json"
	}
	codec, ok := c.codecs[name]
	if !ok {
		return nil, sdkerrors.New(sdkerrors.KindInput,
			"unknown codec for operation").WithOp(op).WithField("codec="+name)
	}
	body, err := codec.Marshal(req.Input)
	if err != nil {
		if se := sdkerrors.AsError(err); se != nil {
			return nil, se.WithOp(op)
		}
		return nil, sdkerrors.New(sdkerrors.KindRuntime, "request encoding failed").WithOp(op).Wrap(err)
	}
	raw, err := c.transport.Call(ctx, &PreparedRequest{
		Service: req.Service, Version: req.Version,
		Operation: req.Operation, Body: body,
	})
	if err != nil {
		return nil, Normalize(op, 0, err)
	}
	if raw == nil {
		return nil, Normalize(op, 0, errNilResponse{})
	}
	if nerr := Normalize(op, raw.Status, nil); nerr != nil {
		return nil, nerr
	}
	if out != nil {
		if err := codec.Unmarshal(raw.Body, out); err != nil {
			return nil, err
		}
	}
	return &Response{Raw: raw.Body}, nil
}

type errNilResponse struct{}

func (errNilResponse) Error() string { return "transport returned nil response without error" }
`
}

func scaffoldLocalTransport() string {
	return `// Code generated by sdkgen; DO NOT EDIT BY HAND.
package runtime

import (
	"context"
)

// HandlerFunc is one local operation implementation.
type HandlerFunc func(ctx context.Context, body []byte) (*RawResponse, error)

// LocalTransport is an in-process transport for offline verification.
type LocalTransport struct {
	routes map[string]HandlerFunc
}

// NewLocalTransport creates an empty local transport.
func NewLocalTransport() *LocalTransport {
	return &LocalTransport{routes: map[string]HandlerFunc{}}
}

// Handle registers a handler for "service.operation".
func (t *LocalTransport) Handle(service, operation string, h HandlerFunc) {
	t.routes[service+"."+operation] = h
}

// Call implements Transport.
func (t *LocalTransport) Call(ctx context.Context, req *PreparedRequest) (*RawResponse, error) {
	h, ok := t.routes[req.Service+"."+req.Operation]
	if !ok {
		return nil, &routeError{service: req.Service, operation: req.Operation}
	}
	return h(ctx, req.Body)
}

type routeError struct{ service, operation string }

func (e *routeError) Error() string {
	return "no local handler registered for " + e.service + "." + e.operation
}
`
}

// importPlaceholder is replaced by the module path in the emitted source.
func importPlaceholder() string { return "__MODULE__" }
