// renderGoSDK produces the files of a self-contained Go SDK package. The
// generated package does not depend on the toolchain at runtime: it carries
// its own normalized error types and a Backend interface the host app
// implements.
func renderGoSDK(b *schema.Bundle, pkgName string) ([]artifact, error) {
	specs := []struct {
		rel  string
		body string
	}{
		{"doc.go", renderDocGo(b, pkgName)},
		{"errors.go", renderErrorsGo(pkgName)},
		{"types.go", renderTypesGo(b, pkgName)},
		{"client.go", renderClientGo(b, pkgName)},
	}
	if smoke, ok := renderSmokeTest(b, pkgName, isEnumSet(b)); ok {
		specs = append(specs, struct {
			rel  string
			body string
		}{"smoke_test.go", smoke})
	}
	files := make([]artifact, 0, len(specs))
	for _, sp := range specs {
		formatted, err := formatGo(sp.rel, []byte(sp.body))
		if err != nil {
			return nil, err
		}
		files = append(files, artifact{relPath: sp.rel, content: formatted})
	}
	return files, nil
}

func isEnumSet(b *schema.Bundle) map[string]bool {
	m := map[string]bool{}
	for _, d := range b.Documents {
		for _, e := range d.Enums {
			m[e.Name] = true
		}
	}
	return m
}

func renderDocGo(b *schema.Bundle, pkgName string) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by versioned-sdk-toolchain-go; DO NOT EDIT.\n")
	fmt.Fprintf(&sb, "// Service: %s  Version: %s\n\n", b.Documents[0].Service, b.Documents[0].Version)
	fmt.Fprintf(&sb, "// Package %s is the generated SDK. Implements a Backend to\n", pkgName)
	fmt.Fprintf(&sb, "// transport calls; the SDK handles encoding, metadata and error\n")
	fmt.Fprintf(&sb, "// normalization.\n")
	fmt.Fprintf(&sb, "package %s\n", pkgName)
	return sb.String()
}

func renderErrorsGo(pkgName string) string {
	return fmt.Sprintf(`// Code generated by versioned-sdk-toolchain-go; DO NOT EDIT.

package %s

import "fmt"

// ErrorCategory is the stable error class callers switch on.
type ErrorCategory string

// Stable error categories.
const (
	CatInvalidInput        ErrorCategory = "invalid_input"
	CatVersionIncompatible ErrorCategory = "version_incompatible"
	CatInvocationFailed    ErrorCategory = "invocation_failed"
)

// SDKError is the normalized error type returned by every client method.
type SDKError struct {
	Category  ErrorCategory
	Interface string
	Reason    string
	Cause     error
}

func (e *SDKError) Error() string {
	s := string(e.Category)
	if e.Interface != "" {
		s += ": interface=" + e.Interface
	}
	if e.Reason != "" {
		s += ": " + e.Reason
	}
	if e.Cause != nil {
		s += fmt.Sprintf(": caused by %%v", e.Cause)
	}
	return s
}

// Unwrap exposes the wrapped backend error.
func (e *SDKError) Unwrap() error { return e.Cause }

// Code extracts the stable category from any error returned by this package.
func Code(err error) ErrorCategory {
	if err == nil {
		return ""
	}
	if se, ok := err.(*SDKError); ok {
		return se.Category
	}
	return CatInvocationFailed
}
`, pkgName)
}

func goPrimitive(p schema.Primitive) string {
	switch p {
	case schema.PrimString:
		return "string"
	case schema.PrimInt:
		return "int32"
	case schema.PrimLong:
		return "int64"
	case schema.PrimFloat:
		return "float32"
	case schema.PrimDouble:
		return "float64"
	case schema.PrimBool:
		return "bool"
	case schema.PrimBytes:
		return "[]byte"
	case schema.PrimTimestamp:
		return "string"
	default:
		return "any"
	}
}

func renderType(t schema.TypeRef, isEnum map[string]bool) string {
	var base string
	switch t.Kind() {
	case "primitive":
		base = goPrimitive(t.Primitive)
	case "ref":
		if isEnum[t.Name] {
			base = t.Name
		} else {
			base = "*" + t.Name
		}
	case "array":
		base = "[]" + renderType(*t.Array, isEnum)
	case "map":
		base = "map[string]" + renderType(*t.MapValue, isEnum)
	default:
		base = "any"
	}
	return base
}

func exportedName(s string) string {
	// Inputs are already expected to use exported Go-friendly identifiers;
	// upper-case the first rune defensively.
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func renderTypesGo(b *schema.Bundle, pkgName string) string {
	isEnum := map[string]bool{}
	for _, d := range b.Documents {
		for _, e := range d.Enums {
			isEnum[e.Name] = true
		}
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by versioned-sdk-toolchain-go; DO NOT EDIT.\n\npackage %s\n\n", pkgName)
	// Render enums first (stable order, de-duplicated).
	seen := map[string]bool{}
	var enums []schema.Enum
	var structs []schema.Struct
	for _, d := range b.Documents {
		for _, e := range d.Enums {
			if !seen[e.Name] {
				seen[e.Name] = true
				enums = append(enums, e)
			}
		}
	}
	seen2 := map[string]bool{}
	for _, d := range b.Documents {
		for _, s := range d.Structs {
			if !seen2[s.Name] {
				seen2[s.Name] = true
				structs = append(structs, s)
			}
		}
	}
	sortEnums(enums)
	for _, e := range enums {
		fmt.Fprintf(&sb, "// %s enumeration.\ntype %s string\n\nconst (\n", e.Name, e.Name)
		for _, v := range e.Values {
			fmt.Fprintf(&sb, "\t%s%s %s = %q\n", e.Name, exportedName(v), e.Name, v)
		}
		sb.WriteString(")\n\n")
	}
	sortStructs(structs)
	for _, s := range structs {
		fmt.Fprintf(&sb, "// %s struct.\ntype %s struct {\n", s.Name, s.Name)
		for _, f := range s.Fields {
			tag := fmt.Sprintf("`json:%q`", f.Name)
			fmt.Fprintf(&sb, "\t%s %s %s\n", exportedName(f.Name), renderType(f.Type, isEnum), tag)
		}
		sb.WriteString("}\n\n")
	}
	return sb.String()
}

func renderClientGo(b *schema.Bundle, pkgName string) string {
	ver := b.Documents[0].Version.String()
	service := b.Documents[0].Service
	isEnum := map[string]bool{}
	for _, d := range b.Documents {
		for _, e := range d.Enums {
			isEnum[e.Name] = true
		}
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, `// Code generated by versioned-sdk-toolchain-go; DO NOT EDIT.

package %s

import (
	"context"
	"encoding/json"
)

// ServiceName is the name of the described service.
const ServiceName = %q

// APIVersion is the pinned version of this SDK.
const APIVersion = %q

// Backend transports one encoded call. Implement it with your HTTP/RPC
// client. Returning a non-nil error normalizes to an SDKError with category
// invocation_failed; the raw error is wrapped, not leaked directly.
type Backend interface {
	Invoke(ctx context.Context, interfaceName, method string, payload []byte) ([]byte, error)
}

// Client is the entry point for all generated calls.
type Client struct {
	backend Backend
}

// New creates a client bound to a backend.
func New(backend Backend) *Client { return &Client{backend: backend} }

func (c *Client) call(ctx context.Context, iface, method string, in any) (json.RawMessage, error) {
	if c.backend == nil {
		return nil, &SDKError{Category: CatInvalidInput, Interface: iface, Reason: "nil backend"}
	}
	payload, err := json.Marshal(in)
	if err != nil {
		return nil, &SDKError{Category: CatInvalidInput, Interface: iface, Reason: "failed to encode request", Cause: err}
	}
	out, err := c.backend.Invoke(ctx, iface, method, payload)
	if err != nil {
		return nil, &SDKError{Category: CatInvocationFailed, Interface: iface, Reason: "backend call failed", Cause: err}
	}
	return json.RawMessage(out), nil
}
`, pkgName, service, ver)

	seen := map[string]bool{}
	for _, d := range b.Documents {
		for _, ifc := range d.Interfaces {
			if seen[ifc.Name] {
				continue
			}
			seen[ifc.Name] = true
			writeMethod(&sb, ifc, isEnum)
		}
	}
	return sb.String()
}

// requestStruct renders the input wrapper for one interface call.
func requestStructName(iface string) string { return iface + "Request" }

func writeMethod(sb *strings.Builder, ifc schema.Interface, isEnum map[string]bool) {
	// Input struct.
	fmt.Fprintf(sb, "// %s is the request payload for %s.\ntype %s struct {\n",
		requestStructName(ifc.Name), ifc.Name, requestStructName(ifc.Name))
	for _, p := range ifc.Input {
		fmt.Fprintf(sb, "\t%s %s `json:%q`\n", exportedName(p.Name), renderType(p.Type, isEnum), p.Name)
	}
	sb.WriteString("}\n\n")

	outType := ""
	if ifc.Output != nil {
		outType = renderType(*ifc.Output, isEnum)
	}
	if outType == "" {
		fmt.Fprintf(sb, "// %s performs the %q operation.\nfunc (c *Client) %s(ctx context.Context, req *%s) error {\n",
			exportedName(ifc.Name), ifc.Method, exportedName(ifc.Name), requestStructName(ifc.Name))
		sb.WriteString("\tif req == nil {\n")
		fmt.Fprintf(sb, "\t\treturn &SDKError{Category: CatInvalidInput, Interface: %q, Reason: \"nil request\"}\n\t}\n", ifc.Name)
		fmt.Fprintf(sb, "\t_, err := c.call(ctx, %q, %q, req)\n", ifc.Name, ifc.Method)
		sb.WriteString("\treturn err\n}\n\n")
		return
	}
	// Structs are rendered as *Struct; arrays/maps as []T / map[...]T;
	// scalars and enums need a pointer wrapper for the decode target.
	retType := outType
	decodeType := strings.TrimPrefix(outType, "*")
	switch ifc.Output.Kind() {
	case "primitive":
		retType = "*" + outType
	case "ref":
		if isEnum[ifc.Output.Name] {
			retType = "*" + outType
		}
	}
	fmt.Fprintf(sb, "// %s performs the %q operation.\nfunc (c *Client) %s(ctx context.Context, req *%s) (%s, error) {\n",
		exportedName(ifc.Name), ifc.Method, exportedName(ifc.Name), requestStructName(ifc.Name), retType)
	sb.WriteString("\tif req == nil {\n")
	fmt.Fprintf(sb, "\t\treturn nil, &SDKError{Category: CatInvalidInput, Interface: %q, Reason: \"nil request\"}\n\t}\n", ifc.Name)
	fmt.Fprintf(sb, "\traw, err := c.call(ctx, %q, %q, req)\n", ifc.Name, ifc.Method)
	sb.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	switch ifc.Output.Kind() {
	case "array", "map":
		fmt.Fprintf(sb, "\tout := %s{}\n", retType)
		fmt.Fprintf(sb, "\tif err := json.Unmarshal(raw, &out); err != nil {\n")
	default:
		fmt.Fprintf(sb, "\tout := &%s{}\n", decodeType)
		fmt.Fprintf(sb, "\tif err := json.Unmarshal(raw, out); err != nil {\n")
	}
	fmt.Fprintf(sb, "\t\treturn nil, &SDKError{Category: CatInvocationFailed, Interface: %q, Reason: \"failed to decode response\", Cause: err}\n\t}\n", ifc.Name)
	sb.WriteString("\treturn out, nil\n}\n\n")
}
