package codegen

import (
	"fmt"
	"strings"

	"github.com/highcumontoa/versioned-sdk-toolchain-go/pkg/schema"
)

// renderSmokeTest emits a self-contained smoke test inside every generated
// SDK that has at least one callable interface. It uses a scripted
// in-memory backend, asserts a successful call decodes output, and asserts
// raw backend errors normalize to CatInvocationFailed. When the schema has
// no interface at all, no test file is emitted (caller skips the artifact).
func renderSmokeTest(b *schema.Bundle, pkgName string, isEnum map[string]bool) (string, bool) {
	var chosen *schema.Interface
	for _, d := range b.Documents {
		for i := range d.Interfaces {
			chosen = &d.Interfaces[i]
			break
		}
		if chosen != nil {
			break
		}
	}
	if chosen == nil {
		return "", false
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by versioned-sdk-toolchain-go; DO NOT EDIT.\n\npackage %s\n\n", pkgName)
	sb.WriteString(`import (
	"context"
	"errors"
	"testing"
)

type smokeBackend struct {
	out []byte
	err error
}

func (s *smokeBackend) Invoke(ctx context.Context, interfaceName, method string, payload []byte) ([]byte, error) {
	return s.out, s.err
}

func TestSmokeBackendErrorNormalized(t *testing.T) {
	c := New(&smokeBackend{err: errors.New("simulated transport outage")})
	err := firstCallError(c)
	if Code(err) != CatInvocationFailed {
		t.Fatalf("generated SDK did not normalize backend error, category=%q err=%v", Code(err), err)
	}
}
`)
	writeSmokeCase(&sb, chosen, isEnum)
	return sb.String(), true
}

func writeSmokeCase(sb *strings.Builder, ifc *schema.Interface, isEnum map[string]bool) {
	method := exportedName(ifc.Name)
	reqType := requestStructName(ifc.Name)

	if ifc.Output == nil {
		fmt.Fprintf(sb, `
func firstCallError(c *Client) error {
	return c.%[1]s(context.Background(), &%[2]s{})
}

func TestSmokeCall(t *testing.T) {
	backend := &smokeBackend{}
	c := New(backend)
	if err := c.%[1]s(context.Background(), &%[2]s{}); err != nil {
		t.Fatalf("interface=%[3]s version=%%s smoke call failed: %%v", APIVersion, err)
	}
}
`, method, reqType, ifc.Name)
		return
	}

	fmt.Fprintf(sb, `
func firstCallError(c *Client) error {
	_, err := c.%[1]s(context.Background(), &%[2]s{})
	return err
}

func TestSmokeSuccessSemantics(t *testing.T) {
	backend := &smokeBackend{out: []byte(%[4]s)}
	c := New(backend)
	out, err := c.%[1]s(context.Background(), &%[2]s{})
	if err != nil {
		t.Fatal(err)
	}
	if out == nil {
		t.Fatal("successful call returned nil output")
	}
	t.Logf("interface=%[3]s version=%%s smoke call ok: %%+v", APIVersion, out)
}
`,
		method, reqType, ifc.Name,
		"`"+sampleJSONFor(*ifc.Output, isEnum)+"`")
}

// sampleJSONFor builds a decodable empty JSON value for the output type so
// the smoke test compiles and runs against any schema. Enum references are
// scalar strings, not objects.
func sampleJSONFor(t schema.TypeRef, isEnum map[string]bool) string {
	switch t.Kind() {
	case "array":
		return "[]"
	case "ref":
		if isEnum[t.Name] {
			return `""`
		}
		return "{}"
	case "map":
		return "{}"
	case "primitive":
		switch t.Primitive {
		case schema.PrimBool:
			return "false"
		case schema.PrimString, schema.PrimBytes, schema.PrimTimestamp:
			return `""`
		default:
			return "0"
		}
	default:
		return "{}"
	}
}
